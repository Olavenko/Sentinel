    private static int Main()
    {
        int passed = 0;
        int failed = 0;

        Console.WriteLine("ConquerCipher standalone verification");
        Console.WriteLine();

        foreach (CipherTestCase testCase in TestCases)
        {
            byte[] encrypted = ParseHex(testCase.EncryptedHex);
            byte[] expected = ParseHex(testCase.ExpectedHex);
            byte[] actual = (byte[])encrypted.Clone();

            int counterA = testCase.CounterA;
            int counterB = testCase.CounterB;

            Transform(actual, 0, actual.Length, ref counterA, ref counterB);

            bool pass = actual.AsSpan().SequenceEqual(expected);
            if (pass)
            {
                passed++;
            }
            else
            {
                failed++;
            }

            Console.WriteLine(
                $"{(pass ? "PASS" : "FAIL")} {testCase.SessionName} {testCase.Timestamp} {testCase.Direction} {testCase.PacketId} " +
                $"ctx=0x{testCase.Context:x} startCounter=({testCase.CounterA},{testCase.CounterB}) len={encrypted.Length}");
            Console.WriteLine($"  encrypted: {ToHex(encrypted)}");
            Console.WriteLine($"  expected : {ToHex(expected)}");
            Console.WriteLine($"  actual   : {ToHex(actual)}");
            Console.WriteLine($"  endCounter=({counterA},{counterB})");

            if (!pass)
            {
                Console.WriteLine($"  mismatch : {DescribeMismatch(expected, actual)}");
            }

            Console.WriteLine();
        }

        Console.WriteLine($"Summary: total tests={TestCases.Length}, passed={passed}, failed={failed}");
        return failed == 0 ? 0 : 1;
    }

    private static byte[] ParseHex(string hex)
    {
        return Convert.FromHexString(hex);
    }

    private static string ToHex(byte[] bytes)
    {
        return Convert.ToHexString(bytes).ToLowerInvariant();
    }

    private static string DescribeMismatch(byte[] expected, byte[] actual)
    {
        if (expected.Length != actual.Length)
        {
            return $"length differs expected={expected.Length} actual={actual.Length}";
        }

        for (int i = 0; i < expected.Length; i++)
        {
            if (expected[i] != actual[i])
            {
                return $"first diff at byte {i}: expected=0x{expected[i]:x2} actual=0x{actual[i]:x2}";
            }
        }

        return "unknown mismatch";
    }

    /// <summary>
    /// Transforms (encrypts or decrypts) <paramref name="length"/> bytes of
    /// <paramref name="buffer"/> in-place starting at <paramref name="offset"/>.
    /// </summary>
    /// <remarks>
    /// The transform is self-inverse: applying it twice returns the original data.
    /// Per-byte steps:
    /// <list type="number">
    ///   <item><description><c>b ^= TableA[counterA]</c></description></item>
    ///   <item><description><c>b ^= TableB[counterB]</c></description></item>
    ///   <item><description>Advance counters: <c>counterA</c> wraps at 0xFF and triggers <c>counterB</c> increment.</description></item>
    ///   <item><description><c>b = ((b &lt;&lt; 4) | (b &gt;&gt; 4)) ^ 0xAB</c> (nibble swap + XOR)</description></item>
    /// </list>
    /// </remarks>
    /// <param name="buffer">Buffer to transform.</param>
    /// <param name="offset">Start offset within <paramref name="buffer"/>.</param>
    /// <param name="length">Number of bytes to process.</param>
    /// <param name="counterA">Rolling index into <see cref="TableA"/>; updated in place.</param>
    /// <param name="counterB">Rolling index into <see cref="TableB"/>; updated in place.</param>
    private static void Transform(byte[] buffer, int offset, int length, ref int counterA, ref int counterB)
    {
        int end = offset + length;
        for (int i = offset; i < end; i++)
        {
            byte b = buffer[i];
            b ^= TableA[counterA];
            b ^= TableB[counterB];

            if (++counterA > 0xFF)
            {
                counterA = 0;
                if (++counterB > 0xFF)
                {
                    counterB = 0;
                }
            }

            buffer[i] = (byte)(((b << 4) | (b >> 4)) ^ 0xAB);
        }
    }

