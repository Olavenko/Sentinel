Interceptor.attach(customCipherAddr, {
    onEnter: function (args) {
        var ctx = this.context.ecx;
        var buf = args[0];
        var len = args[1].toInt32();
        var commit = args[2].toInt32();

        if (callCount >= MAX_VALIDATE) return;

        this.shouldValidate = true;
        this.callIndex = callCount;
        this.ctx = ctx;
        this.buf = buf;
        this.len = len;
        this.commit = commit;

        var ctxKey = ctx.toString();

        // Initialize counter tracking for this context
        if (!ctxCounters[ctxKey]) {
            ctxCounters[ctxKey] = { counterA: 0, counterB: 0 };
        }

        // Read game's counters before call
        var gameCA = safeReadU32(ctx);
        var gameCB = safeReadU32(ctx.add(0x04));

        this.gameCA = gameCA;
        this.gameCB = gameCB;
        this.ourCA = ctxCounters[ctxKey].counterA;
        this.ourCB = ctxCounters[ctxKey].counterB;

        // Capture encrypted input BEFORE the game modifies it
        var captureLen = len > 64 ? 64 : len;  // cap preview at 64 bytes
        this.capturedEncrypted = [];
        for (var i = 0; i < captureLen; i++) {
            try {
                this.capturedEncrypted.push(buf.add(i).readU8());
            } catch (e) {
                this.capturedEncrypted.push(0);
            }
        }
        this.captureLen = captureLen;

        callCount++;
    },

    onLeave: function (retval) {
        if (!this.shouldValidate) return;

        var ctxKey = this.ctx.toString();

        // Read game's decrypted output
        var gameDecrypted = [];
        for (var i = 0; i < this.captureLen; i++) {
            try {
                gameDecrypted.push(this.buf.add(i).readU8());
            } catch (e) {
                gameDecrypted.push(0);
            }
        }

        // Apply OUR decryption to the captured encrypted bytes
        var ourResult = ourDecrypt(this.capturedEncrypted, this.ourCA, this.ourCB);
        var ourDecrypted = ourResult.bytes;

        // Compare
        var match = true;
        for (var i = 0; i < this.captureLen; i++) {
            if (ourDecrypted[i] !== gameDecrypted[i]) {
                match = false;
                break;
            }
        }

        if (match) {
            matchCount++;
        } else {
            mismatchCount++;
        }

        var encHex = bytesToHex(this.capturedEncrypted);
        var gameHex = bytesToHex(gameDecrypted);
        var ourHex = bytesToHex(ourDecrypted);

        var status = match ? "MATCH" : "MISMATCH";

        logBoth("[VALIDATE #" + this.callIndex + "] " + status
            + " ctx=" + this.ctx
            + " len=" + this.len
            + " commit=" + this.commit
            + " counters(game)=(" + this.gameCA + "," + this.gameCB + ")"
            + " counters(ours)=(" + this.ourCA + "," + this.ourCB + ")");

        log("  encrypted: " + encHex);
        log("  game_dec:  " + gameHex);
        log("  our_dec:   " + ourHex);

        if (!match) {
            // Find first mismatch position
            for (var i = 0; i < this.captureLen; i++) {
                if (ourDecrypted[i] !== gameDecrypted[i]) {
                    log("  FIRST MISMATCH at byte " + i
                        + ": game=0x" + ('0' + gameDecrypted[i].toString(16)).slice(-2)
                        + " ours=0x" + ('0' + ourDecrypted[i].toString(16)).slice(-2));
                    break;
                }
            }
        }

        // Update OUR counter tracking (only if commit=1)
        if (this.commit === 1) {
            // Advance counters for FULL length (not just captured preview)
            var cA = this.ourCA;
            var cB = this.ourCB;
            for (var i = 0; i < this.len; i++) {
                if (++cA > 0xFF) {
                    cA = 0;
                    if (++cB > 0xFF) cB = 0;
                }
            }
            ctxCounters[ctxKey].counterA = cA;
            ctxCounters[ctxKey].counterB = cB;
        }
    }
});

