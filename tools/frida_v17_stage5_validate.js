// --- Our implementation of the cipher ---
function ourDecrypt(encBytes, counterA, counterB) {
    var result = [];
    var cA = counterA;
    var cB = counterB;

    for (var i = 0; i < encBytes.length; i++) {
        var b = encBytes[i];
        b ^= TABLE_A[cA];
        b ^= TABLE_B[cB];
        if (++cA > 0xFF) {
            cA = 0;
            if (++cB > 0xFF) cB = 0;
        }
        b = ((b << 4) | (b >> 4)) & 0xFF;
        b ^= 0xAB;
        result.push(b);
    }

    return { bytes: result, counterA: cA, counterB: cB };
}

function bytesToHex(arr) {
    var out = "";
    for (var i = 0; i < arr.length; i++) {
        out += ('0' + arr[i].toString(16)).slice(-2);
    }
    return out;
}

function hexToBytes(hexStr) {
    var bytes = [];
    for (var i = 0; i < hexStr.length; i += 2) {
        bytes.push(parseInt(hexStr.substr(i, 2), 16));
    }
    return bytes;
}

