// --- State ---
var callCount = 0;
var MAX_VALIDATE = 10;
var matchCount = 0;
var mismatchCount = 0;

// Track counters per context
var ctxCounters = {};  // ctx_addr -> { counterA, counterB }

logBoth("[*] Frida v17 — Stage 5: Cipher Validation");
