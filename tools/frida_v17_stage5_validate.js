function hexN(ptrValue, n) {
    var out = "";
    for (var i = 0; i < n; i++) {
        out += ('0' + ptrValue.add(i).readU8().toString(16)).slice(-2);
    }
    return out;
}

function safeHexN(ptrValue, n) {
    try {
        return hexN(ptrValue, n);
    } catch (e) {
        return "<read-failed>";
    }
}

function safeReadU32(ptrValue) {
    try {
        return ptrValue.readU32();
    } catch (e) {
        return null;
    }
}

