    private static int Main()
    {
        Console.WriteLine("Counter carry test");
        Console.WriteLine($"encrypted: {ToHex(EncryptedPacket)}");
        Console.WriteLine();

        foreach (CounterTestCase testCase in TestCases)
        {
            byte[] decrypted = (byte[])EncryptedPacket.Clone();
            int counterA = testCase.CounterA;
            int counterB = testCase.CounterB;

            Transform(decrypted, 0, decrypted.Length, ref counterA, ref counterB);

            ushort size = BitConverter.ToUInt16(decrypted, 0);
            bool plausible = size < 2048;

            Console.WriteLine($"{testCase.Name} counter=({testCase.CounterA},{testCase.CounterB}) decrypted={ToHex(decrypted)} sizeLE={size} plausible={(plausible ? "YES" : "NO")}");
        }

        return 0;
    }

    private static string ToHex(byte[] bytes)
    {
        return Convert.ToHexString(bytes).ToLowerInvariant();
    }

    private static void Transform(byte[] buffer, int offset, int length, ref int counterA, ref int counterB)
    {
        int end = offset + length;
        for (int i = offset; i < end; i++)
        {
            byte b = buffer[i];
            b ^= TableA[counterA];
            b ^= TableB[counterB];

            if (++counterA > 0xFF)
            {
                counterA = 0;
                if (++counterB > 0xFF)
                {
                    counterB = 0;
                }
            }

            buffer[i] = (byte)(((b << 4) | (b >> 4)) ^ 0xAB);
        }
    }

    private sealed record CounterTestCase(string Name, int CounterA, int CounterB);
