// As implemented in ConquerCipher.cs — matches game's FUN_00fef18a exactly.
// Per Stage 5: 24/24 verified match against live game output.
// Operation: b = nibble_swap(b ^ tableA[cA] ^ tableB[cB]) ^ 0xAB
void Transform(byte[] buf, int offset, int length, ref int cA, ref int cB)
{
    int end = offset + length;
    for (int i = offset; i < end; i++)
    {
        byte b = buf[i];
        b ^= tableA[cA];
        b ^= tableB[cB];
        if (++cA > 0xFF) { cA = 0; if (++cB > 0xFF) cB = 0; }
        buf[i] = (byte)(((b << 4) | (b >> 4)) ^ 0xAB);
    }
}

// Algebraic inverse of Transform.
// Transform:  c = nibble_swap(p ^ tA ^ tB) ^ 0xAB
// Inverse:    p = nibble_swap(c ^ 0xAB)    ^ tA ^ tB
// Proof: InvTransform(Transform(p)) = nibble_swap(nibble_swap(p^tA^tB)^0xAB^0xAB)^tA^tB
//                                   = nibble_swap(nibble_swap(p^tA^tB))^tA^tB
//                                   = (p^tA^tB)^tA^tB = p  ✓
void InvTransform(byte[] buf, int offset, int length, ref int cA, ref int cB)
{
    int end = offset + length;
    for (int i = offset; i < end; i++)
    {
        byte b = buf[i];
        b ^= 0xAB;
        b  = (byte)(((b << 4) | (b >> 4)));   // nibble_swap(c ^ 0xAB)
        b ^= tableA[cA];
        b ^= tableB[cB];
        if (++cA > 0xFF) { cA = 0; if (++cB > 0xFF) cB = 0; }
        buf[i] = b;
    }
}

